import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import path from 'node:path';
import {parsePdb,runGeometry} from '../src/engine/index.js';
import {requestFor} from '../tests/engine-helpers.js';
const base=path.resolve(import.meta.dirname,'..');
const python=process.env.PTM_PYTHON??(process.platform==='win32'?'python':'python3');
const expected=JSON.parse(readFileSync(path.join(base,'fixtures/expected/1BRS-A-D.json'),'utf8'));
const independent=JSON.parse(execFileSync(python,[path.join(import.meta.dirname,'reference_geometry.py')],{encoding:'utf8'}));
assert.deepEqual(independent,expected,'Independent oracle changed from recorded expectations');
const s=parsePdb(readFileSync(path.join(base,'fixtures/structures/1BRS.pdb'),'utf8'),{name:'1BRS.pdb',kind:'bundled-fixture',evidenceClass:'observed-structure'});
const r=runGeometry(s,requestFor(s,'A','D'));
const byKey=new Map(s.atoms.map(a=>[a.key,a.serial]));
const signatures=(pairs:typeof r.contacts)=>pairs.map(p=>`${byKey.get(p.atomAKey)}:${byKey.get(p.atomBKey)}`).sort();
assert.equal(s.source.sha256,expected.sourceSha256);
assert.equal(r.summary.selectedAtomCountA,expected.atomCountA);assert.equal(r.summary.selectedAtomCountB,expected.atomCountB);
assert.equal(r.summary.evaluatedPairCount,expected.evaluatedPairCount);
assert.equal(r.summary.contactCount,expected.contactCount);assert.equal(r.summary.contactResiduePairCount,expected.contactResiduePairCount);
assert.equal(r.summary.clashCandidateCount,expected.clashCandidateCount);
assert.deepEqual(signatures(r.contacts),expected.contactSerialPairs);assert.deepEqual(signatures(r.clashCandidates),expected.overlapSerialPairs);
assert.equal(byKey.get(r.minimumDistance.atomAKey),expected.minimumDistance.serialA);assert.equal(byKey.get(r.minimumDistance.atomBKey),expected.minimumDistance.serialB);
const error=Math.abs(r.minimumDistance.distanceAngstrom-expected.minimumDistance.distanceAngstrom);
assert.ok(error<1e-12);
const report={status:'passed',verifiedAt:new Date().toISOString(),sourceSha256:s.source.sha256,summary:r.summary,minimumDistanceAngstrom:r.minimumDistance.distanceAngstrom,absoluteErrorAngstrom:error,contactPairSetsMatch:true,overlapPairSetsMatch:true,oracle:'Independent Python standard library; no application imports'};
mkdirSync(path.join(base,'evidence'),{recursive:true});
writeFileSync(path.join(base,'evidence/numerical-verification.json'),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report,null,2));
